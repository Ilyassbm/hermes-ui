#!/usr/bin/env node
// Generates src/app/provider-logos.generated.ts from the 13 MIT marks in src/assets/providers.
//
// The marks are lobe-icons SVGs (mono, currentColor, 24×24 except Meta's wordmark). The script reads each file, keeps
// its viewBox and its path data (circles and rectangles are turned into path data so the renderer only ever draws
// `<path>`), and pairs it with the brand colour the spec pins. src/app/provider-logo.tsx is the only consumer.
//
// Run by scripts/build.mjs before esbuild, and by `npm run gen:logos`.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const source = resolve(root, 'src/assets/providers')
const output = resolve(root, 'src/app/provider-logos.generated.ts')

/** Brand colours, checked against each house's chart. Black marks are painted with --text-1 by the component. */
const COLORS = {
  anthropic: '#D97757',
  openai: '#10A37F',
  gemini: '#4285F4',
  deepseek: '#4D6BFE',
  xai: '#000000',
  groq: '#F55036',
  mistral: '#FA520F',
  meta: '#0081FB',
  qwen: '#615CED',
  openrouter: '#6467F2',
  ollama: '#000000',
  opencode: '#211E1E',
  perplexity: '#20808D'
}

const num = (value, fallback = 0) => {
  const n = Number(value)
  return Number.isFinite(n) ? n : fallback
}

/** An SVG circle as one closed path: two half arcs. */
function circlePath(attrs) {
  const cx = num(attrs.cx)
  const cy = num(attrs.cy)
  const r = num(attrs.r)
  return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0Z`
}

/** An SVG rect as a closed path, with its corners rounded when rx says so. */
function rectPath(attrs) {
  const x = num(attrs.x)
  const y = num(attrs.y)
  const w = num(attrs.width)
  const h = num(attrs.height)
  const r = Math.min(num(attrs.rx, num(attrs.ry)), w / 2, h / 2)
  if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`
  return (
    `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}` +
    `a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}` +
    `v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`
  )
}

/** The attributes of one tag, as a plain object (double, then single quotes — these files are machine-written). */
function attributes(tag) {
  const out = {}
  for (const match of tag.matchAll(/([a-zA-Z_:][-a-zA-Z0-9_:.]*)\s*=\s*"([^"]*)"/g)) out[match[1]] = match[2]
  return out
}

function readSvg(file) {
  const svg = readFileSync(file, 'utf8')
  const box = /\bviewBox="([^"]+)"/.exec(svg)?.[1] || '0 0 24 24'
  const paths = []
  // `path`, `circle` and `rect` only: the marks carry no other drawable. A transform is kept as it is; Meta's
  // wordmark positions twelve of its paths with translate(2 2).
  for (const match of svg.matchAll(/<(path|circle|rect)\b([^>]*)>/g)) {
    const tag = match[1]
    const attrs = attributes(match[2])
    let d = ''
    if (tag === 'path') d = attrs.d || ''
    else if (tag === 'circle') d = circlePath(attrs)
    else d = rectPath(attrs)
    if (!d.trim()) continue
    /** @type {{ d: string, transform?: string }} */
    const entry = { d }
    if (attrs.transform) entry.transform = attrs.transform
    // Gemini repeats one shape once per gradient layer; with a mono fill the copies are the same ink, so keep one.
    if (!paths.some(other => other.d === entry.d && other.transform === entry.transform)) paths.push(entry)
  }
  return { box, paths }
}

const files = readdirSync(source)
  .filter(name => name.endsWith('.svg'))
  .sort()

const logos = {}
for (const file of files) {
  const id = file.replace(/\.svg$/, '')
  const { box, paths } = readSvg(join(source, file))
  logos[id] = { box, paths, color: COLORS[id] || '#000000' }
}

const body = [
  '// Generated by scripts/gen-provider-logos.mjs — do not edit by hand.',
  '// Source: src/assets/providers (MIT, lobe-icons; see the LICENSE beside the SVGs).',
  '',
  'export type ProviderLogoPath = { d: string; transform?: string }',
  '',
  'export type ProviderLogoData = { box: string; paths: ProviderLogoPath[]; color: string }',
  '',
  'export const PROVIDER_LOGOS: Record<string, ProviderLogoData> = ' + JSON.stringify(logos, null, 2),
  ''
].join('\n')

writeFileSync(output, body)
console.log(`gen-provider-logos: ${files.length} icons → ${output}`)
